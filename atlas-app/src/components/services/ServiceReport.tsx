import type { ServiceReportData } from '@/server/job-report';
import { PrintButton } from './PrintButton';

/**
 * The printable service report (workflow slice 6). White paper, black text
 * whatever the theme - it is meant to be printed or saved as a PDF.
 */
const d = (x: Date | null) => (x ? x.toLocaleString('en-IN', { timeZone: 'Asia/Kolkata', day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' }) : '-');
const dur = (s: number) => (s <= 0 ? '-' : s >= 3600 ? `${Math.floor(s / 3600)} h ${Math.floor((s % 3600) / 60)} min` : `${Math.max(1, Math.round(s / 60))} min`);

export function ServiceReport({ r }: { r: ServiceReportData }) {
  const row = 'border-b border-gray-300 py-1.5';
  return (
    <main className="mx-auto max-w-3xl bg-white p-6 text-black sm:p-10">
      <div className="mb-4 flex justify-end print:hidden"><PrintButton /></div>
      <div className="flex flex-wrap items-start justify-between gap-4 border-b-2 border-black pb-4">
        <div>
          <h1 className="text-xl font-bold">{r.businessName}</h1>
          <p className="text-xs">{r.branchName}{r.branchAddress ? ` · ${r.branchAddress}` : ''}</p>
        </div>
        <div className="text-end">
          <h2 className="text-lg font-bold">SERVICE REPORT</h2>
          <p className="font-mono text-sm">{r.complaintNo}</p>
          <p className="text-xs">{r.statusLabel}</p>
        </div>
      </div>

      <table className="mt-4 w-full text-sm">
        <tbody>
          <tr><td className={`${row} w-44 font-semibold`}>Customer</td><td className={row}>{r.customerName} · {r.customerPhone}</td></tr>
          {r.siteLocation && <tr><td className={`${row} font-semibold`}>Site</td><td className={row}>{r.siteLocation}</td></tr>}
          {r.productName && <tr><td className={`${row} font-semibold`}>Equipment</td><td className={row}>{r.productName}</td></tr>}
          <tr><td className={`${row} font-semibold`}>Problem reported</td><td className={row}>{r.problem}</td></tr>
          <tr><td className={`${row} font-semibold`}>Raised</td><td className={row}>{d(r.raisedAt)}</td></tr>
          <tr><td className={`${row} font-semibold`}>Technician</td><td className={row}>{r.technicianName ?? '-'}</td></tr>
          <tr><td className={`${row} font-semibold`}>Visits</td><td className={row}>{r.visits.length ? r.visits.map((v) => d(v.at)).join(' · ') : '-'}</td></tr>
          <tr><td className={`${row} font-semibold`}>Time on site</td><td className={row}>{dur(r.timeOnSiteSec)}</td></tr>
          <tr><td className={`${row} font-semibold`}>Work done</td><td className={row}>{r.workDone.length ? r.workDone.join(' / ') : '-'}</td></tr>
          <tr><td className={`${row} font-semibold`}>Parts used</td><td className={row}>{r.parts.length ? r.parts.map((p) => `${p.name} × ${p.qty}`).join(', ') : 'None'}</td></tr>
          <tr><td className={`${row} font-semibold`}>Resolved</td><td className={row}>{d(r.resolvedAt)}</td></tr>
          <tr><td className={`${row} font-semibold`}>Closed</td><td className={row}>{d(r.closedAt)}</td></tr>
          <tr><td className={`${row} font-semibold`}>Confirmation</td><td className={row}>{r.confirmation}</td></tr>
          {r.rating && <tr><td className={`${row} font-semibold`}>Customer rating - the work</td><td className={row}>{'★'.repeat(r.rating)}{'☆'.repeat(5 - r.rating)}</td></tr>}
          {r.techRating && <tr><td className={`${row} font-semibold`}>Customer rating - the technician</td><td className={row}>{'★'.repeat(r.techRating)}{'☆'.repeat(5 - r.techRating)}</td></tr>}
        </tbody>
      </table>
      <p className="mt-6 text-xs text-gray-600">Generated by Atlas. Keep this report for your records.</p>
    </main>
  );
}
