-- Gives every non-Admin role a sidebar.
--
-- Menu visibility is a third tier on top of permissions, and the resolver
-- reads a MISSING RoleMenuConfig row as not-visible (administration.ts:
-- `roleMap.get(...) ?? false`). The six roles created for this tenant had
-- permissions but no menu rows, so all 26 staff logins could sign in and
-- see a blank sidebar. Only Admin had rows.
--
-- Each routed menu is matched to the permission that gates its page; a role
-- sees it when it holds that permission. Group headers, which have no route,
-- are visible when any child of theirs is. Keyed on role NAME and menu
-- ROUTE rather than ids, so it applies on any database.

