     ORDER BY (SELECT count(*) FROM "Invoice" i WHERE i."storeId" = s.id) DESC LIMIT 1) AND m.reason = 'migration_backfill' AND m."refType" = 'GoodsReceiptNote'
   AND m."refId" = g.id AND m."createdAt" < '1971-01-01';

-- Opening balances go back to one minute before their product's first replayed movement.
UPDATE "StockMovement" m SET "createdAt" = x.first_at - interval '1 minute'
  FROM (SELECT "productId", min("createdAt") AS first_at FROM "StockMovement"
         WHERE "storeId" = (SELECT s.id FROM "Store" s JOIN "Organization" o ON o.id = s."organizationId"
     WHERE o.name ILIKE '%vcare%' OR o.name ILIKE '%v.care%'
     ORDER BY (SELECT count(*) FROM "Invoice" i WHERE i."storeId" = s.id) DESC LIMIT 1) AND reason = 'migration_backfill' GROUP BY 1) x
 WHERE m."storeId" = (SELECT s.id FROM "Store" s JOIN "Organization" o ON o.id = s."organizationId"
     WHERE o.name ILIKE '%vcare%' OR o.name ILIKE '%v.care%'
     ORDER BY (SELECT count(*) FROM "Invoice" i WHERE i."storeId" = s.id) DESC LIMIT 1) AND m.reason = 'migration_opening' AND m."productId" = x."productId"
   AND m."createdAt" < '1971-01-01';

-- Running balances on the migrated rows, recomputed in the corrected date order
-- (opening first, then by date, then by row id so ties always break the same way).
UPDATE "StockMovement" m SET "balanceAfter" = r.running
  FROM (SELECT id, (sum(qty) OVER (PARTITION BY "productId"
          ORDER BY "createdAt", CASE WHEN reason = 'migration_opening' THEN 0 ELSE 1 END, "refId", id
          ROWS UNBOUNDED PRECEDING))::int AS running
          FROM "StockMovement" WHERE "storeId" = (SELECT s.id FROM "Store" s JOIN "Organization" o ON o.id = s."organizationId"
     WHERE o.name ILIKE '%vcare%' OR o.name ILIKE '%v.care%'
     ORDER BY (SELECT count(*) FROM "Invoice" i WHERE i."storeId" = s.id) DESC LIMIT 1) AND reason IN ('migration_opening', 'migration_backfill')) r
 WHERE m.id = r.id AND m."balanceAfter" <> r.running;
