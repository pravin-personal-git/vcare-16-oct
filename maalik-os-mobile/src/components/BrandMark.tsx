import { Image, View } from 'react-native';
import { Text } from './ui';
import { font } from '@/theme/tokens';

const MARK_WHITE = require('../../assets/brand/mark-white.png');
const MARK_INK = require('../../assets/brand/mark-ink.png');
// The shield is TALLER than it is wide, where the old M mark was wider
// than tall (13 Oct 2026). Printed by scripts/brand-assets.cjs.
const MARK_RATIO = 224 / 256;

/**
 * The Vcare shield with the name beside it - the app's header brand.
 * `onDark` picks the white artwork for dark surfaces (the hero, dark mode);
 * otherwise the ink artwork. Artwork generated by scripts/brand-assets.cjs.
 */
export function BrandMark({ onDark, color, size = 28, wordmark = true }: {
  onDark: boolean; color: string; size?: number; wordmark?: boolean;
}) {
  return (
    <View style={{ flexDirection: 'row', alignItems: 'center', gap: 10 }} accessibilityLabel="Vcare">
      <Image source={onDark ? MARK_WHITE : MARK_INK} style={{ height: size, width: size * MARK_RATIO }} resizeMode="contain" />
      {/*
        Letter-spacing dropped from 1.5 to 0.4 (13 Oct 2026). The old wordmark
        was MAALIK OS - nine capitals, which wide spacing suits. "Vcare" is
        five mixed-case letters, and the same spacing left it looking pulled
        apart beside the shield.
      */}
      {wordmark && (
        <Text weight="bold" color={color} style={{ fontFamily: font.brand, fontSize: 17, letterSpacing: 0.4 }}>Vcare</Text>
      )}
    </View>
  );
}
